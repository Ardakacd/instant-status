#!/usr/bin/env node
/**
 * Generates public/firebase-config.js from environment variables.
 * Run before deploying to Firebase Hosting so the web pages (verify, reset-password)
 * use the correct Firebase config for each environment.
 *
 * Usage: node scripts/generate-firebase-config.js
 * Requires: .env with EXPO_PUBLIC_FIREBASE_* variables (or set in CI/CD)
 */

const fs = require("fs");
const path = require("path");

// Load .env if it exists (Expo/dotenv style - we use a simple approach)
const envPath = path.join(__dirname, "..", ".env");
if (fs.existsSync(envPath)) {
  const envContent = fs.readFileSync(envPath, "utf8");
  envContent.split("\n").forEach((line) => {
    const match = line.match(/^([^#=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      const value = match[2].trim().replace(/^["']|["']$/g, "");
      process.env[key] = value;
    }
  });
}

const config = {
  apiKey: process.env.EXPO_PUBLIC_FIREBASE_API_KEY || "",
  authDomain: process.env.EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN || "",
  projectId: process.env.EXPO_PUBLIC_FIREBASE_PROJECT_ID || "",
  storageBucket: process.env.EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET || "",
  messagingSenderId: process.env.EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "",
  appId: process.env.EXPO_PUBLIC_FIREBASE_APP_ID || "",
};

const output = `// Auto-generated by scripts/generate-firebase-config.js - do not edit
// Run before firebase deploy to inject config from .env
window.__FIREBASE_CONFIG__ = ${JSON.stringify(config, null, 2)};
`;

const outPath = path.join(__dirname, "..", "public", "firebase-config.js");
fs.writeFileSync(outPath, output, "utf8");
console.log(`Generated ${outPath}`);
console.log(config);
if (!config.apiKey) {
  console.warn(
    "Warning: EXPO_PUBLIC_FIREBASE_API_KEY is empty. Set it in .env before deploy.",
  );
}
